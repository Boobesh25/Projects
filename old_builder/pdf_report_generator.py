"""
JobRadar PDF Report Generator
==============================
Generates professional, enterprise-grade multi-page PDF evaluation reports using ReportLab.
Includes candidate metadata, match score summaries, and detailed tabular requisition data.
"""

import io
from datetime import datetime
from typing import List, Dict, Any, Optional

from reportlab.lib.pagesizes import letter, landscape
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    """Canvas that computes total page count dynamically for professional footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (on pages after the first)
        if self._pageNumber > 1:
            self.drawString(36, 580, "JobRadar Console — Verified Candidate Evaluation Report")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(36, 574, 756, 574)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(756, 20, footer_text)
        self.drawString(36, 20, "Confidential — Generated by JobRadar Career Intelligence Platform")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 30, 756, 30)
        self.restoreState()


def build_pdf_report(
    candidate_name: str,
    professional_title: str,
    experience_years: float,
    items: List[Dict[str, Any]],
    metrics_summary: Dict[str, Any],
    selected_categories: List[str],
    selected_channels: List[str]
) -> bytes:
    """
    Builds and returns a PDF document as bytes.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(letter),
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=38
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "DocTitle",
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0F172A")
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        fontName="Helvetica",
        fontSize=9.5,
        leading=13,
        textColor=colors.HexColor("#475569")
    )
    section_h2 = ParagraphStyle(
        "SectionH2",
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#1E293B"),
        spaceBefore=8,
        spaceAfter=4
    )
    th_style = ParagraphStyle(
        "TableHeader",
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=colors.white,
        alignment=0
    )
    cell_bold = ParagraphStyle(
        "CellBold",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10.5,
        textColor=colors.HexColor("#0F172A")
    )
    cell_text = ParagraphStyle(
        "CellText",
        fontName="Helvetica",
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#334155")
    )
    cell_channel = ParagraphStyle(
        "CellChannel",
        fontName="Helvetica-Bold",
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#1E40AF")
    )
    cell_score = ParagraphStyle(
        "CellScore",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#047857")
    )
    cell_link = ParagraphStyle(
        "CellLink",
        fontName="Helvetica",
        fontSize=7,
        leading=9,
        textColor=colors.HexColor("#2563EB")
    )

    story = []

    # 1. Header Banner & Title
    story.append(Paragraph("JobRadar Console — Candidate Evaluation Report", title_style))
    story.append(Paragraph("Cross-Platform Employer Requisitions Analysis & Ground Truth Matching", subtitle_style))
    story.append(Spacer(1, 8))

    # 2. Candidate Metadata & Filter Context Table
    now_str = datetime.now().strftime("%B %d, %Y - %H:%M UTC")
    cat_str = ", ".join(selected_categories) if selected_categories else "All Categories"
    chan_str = ", ".join(selected_channels) if selected_channels else "All Channels"

    meta_data = [
        [
            Paragraph(f"<b>Candidate:</b> {candidate_name}", cell_text),
            Paragraph(f"<b>Target Discipline:</b> {professional_title}", cell_text),
            Paragraph(f"<b>Experience:</b> {experience_years} Years", cell_text),
            Paragraph(f"<b>Generated:</b> {now_str}", cell_text)
        ],
        [
            Paragraph(f"<b>Included Categories:</b> {cat_str}", cell_text),
            Paragraph(f"<b>Included Channels:</b> {chan_str}", cell_text),
            Paragraph(f"<b>Total Rows in Report:</b> {len(items)} Roles", cell_text),
            Paragraph(f"<b>Database Tracked Pool:</b> 1,000+ Employers", cell_text)
        ]
    ]

    meta_table = Table(meta_data, colWidths=[180, 180, 180, 180])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F1F5F9")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 10))

    # 3. Metrics Summary Strip
    exact_c = metrics_summary.get("exact_matches_count", 0)
    action_c = metrics_summary.get("action_needed_count", 0)
    cross_c = metrics_summary.get("cross_domain_count", 0)
    div_c = metrics_summary.get("divergent_count", 0)
    noop_c = metrics_summary.get("no_openings_count", 0)

    summary_cells = [
        [
            Paragraph(f"<font color='#16A34A'><b>Exact Matches:</b></font> {exact_c}", cell_bold),
            Paragraph(f"<font color='#CA8A04'><b>Action Needed:</b></font> {action_c}", cell_bold),
            Paragraph(f"<font color='#9333EA'><b>Cross-Domain (Adjacent):</b></font> {cross_c}", cell_bold),
            Paragraph(f"<font color='#DC2626'><b>Role Divergent:</b></font> {div_c}", cell_bold),
            Paragraph(f"<font color='#64748B'><b>0 Openings Monitored:</b></font> {noop_c}", cell_bold)
        ]
    ]
    summary_table = Table(summary_cells, colWidths=[144, 144, 150, 140, 142])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#FFFFFF")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 10))

    # 4. Table of Results
    table_headers = [
        Paragraph("Company Name", th_style),
        Paragraph("Role Title", th_style),
        Paragraph("Channel", th_style),
        Paragraph("Score & Category", th_style),
        Paragraph("Mode / Location", th_style),
        Paragraph("Matched Skills", th_style),
        Paragraph("Missing Skills", th_style),
        Paragraph("Direct Requisition Link", th_style)
    ]

    col_widths = [105, 125, 65, 85, 75, 95, 90, 80]
    table_data = [table_headers]

    for item in items:
        c_name = item.get("company_name", "N/A")
        c_group = item.get("company_group", "")
        r_title = item.get("title", "N/A")
        channel = item.get("source_channel", "Career Page")
        score = item.get("match_score", 0.0)
        cat = item.get("match_category", "Match")
        work_mode = item.get("work_mode", "Unspecified")
        loc = item.get("location", "Global")
        matched_s = ", ".join(item.get("matched_skills", [])[:4]) or "None"
        lag_s = ", ".join(item.get("lag_skills", [])[:3]) or "None"
        url = item.get("job_apply_url") or item.get("url") or ""
        job_id = item.get("job_id", "")

        # Format cell paragraphs
        p_comp = Paragraph(f"<b>{c_name}</b><br/><font color='#64748B'>{c_group}</font>", cell_bold)
        p_title = Paragraph(f"<b>{r_title}</b>", cell_text)
        p_chan = Paragraph(f"<b>{channel}</b>", cell_channel)
        
        # Color score
        if "cross-domain" in cat.lower() or "adjacent" in cat.lower():
            p_score = Paragraph(f"<font color='#9333EA'><b>{score}%</b><br/>Cross-Domain</font>", cell_score)
        elif score >= 75:
            p_score = Paragraph(f"<font color='#16A34A'><b>{score}%</b><br/>Exact Match</font>", cell_score)
        elif score >= 60:
            p_score = Paragraph(f"<font color='#CA8A04'><b>{score}%</b><br/>Action Needed</font>", cell_score)
        else:
            p_score = Paragraph(f"<font color='#DC2626'><b>{score}%</b><br/>Divergent</font>", cell_score)

        p_loc = Paragraph(f"{work_mode}<br/><font color='#64748B'>{loc[:20]}</font>", cell_text)
        p_match = Paragraph(f"<font color='#16A34A'>{matched_s}</font>", cell_text)
        p_lag = Paragraph(f"<font color='#DC2626'>{lag_s}</font>", cell_text)
        
        # Link
        short_link = url if len(url) <= 30 else url[:27] + "..."
        p_link = Paragraph(f"<a href='{url}' color='#2563EB'><u>Apply #{job_id[:12]}</u></a><br/><font color='#64748B'>{short_link}</font>", cell_link)

        table_data.append([p_comp, p_title, p_chan, p_score, p_loc, p_match, p_lag, p_link])

    if len(table_data) == 1:
        # No rows
        table_data.append([
            Paragraph("No matching requisitions found for the selected filter criteria.", cell_text),
            "", "", "", "", "", "", ""
        ])

    results_table = Table(table_data, colWidths=col_widths, repeatRows=1)
    
    # Table Styling
    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1E293B")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
    ]

    # Alternating row colors
    for r_idx in range(1, len(table_data)):
        if r_idx % 2 == 0:
            t_style.append(('BACKGROUND', (0, r_idx), (-1, r_idx), colors.HexColor("#F8FAFC")))
        else:
            t_style.append(('BACKGROUND', (0, r_idx), (-1, r_idx), colors.white))

    results_table.setStyle(TableStyle(t_style))
    story.append(results_table)

    # Build document with NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()
